"""Build print-only KaTeX derivatives with the same advance widths."""
import ctypes
import re
import tempfile
from pathlib import Path

import freetype
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._g_l_y_f import GlyphCoordinates
from fontTools.ttLib.tables.ttProgram import Program

ASSETS = Path(__file__).resolve().parents[1] / "assets"
KATEX = ASSETS / "vendor" / "katex"
OUTPUT = ASSETS / "print-math"
# Outline growth as a fraction of an em. Keep original advances and styles.
INK = 0.018


def strengthen_font(source, output, scratch):
    font = TTFont(source, recalcTimestamp=False)
    font.flavor = None
    font.save(scratch)
    face = freetype.Face(str(scratch))
    flags = freetype.FT_LOAD_NO_SCALE | freetype.FT_LOAD_NO_HINTING | freetype.FT_LOAD_NO_BITMAP
    growth = round(font["head"].unitsPerEm * INK)
    glyf = font["glyf"]
    metrics = font["hmtx"].metrics
    original_x_min = {}
    for index, name in enumerate(font.getGlyphOrder()):
        glyph = glyf[name]
        if glyph.numberOfContours == 0:
            continue
        original_x_min[name] = glyph.xMin
        if glyph.isComposite():
            continue
        face.load_glyph(index, flags)
        outline = face.glyph.outline
        previous = outline.points
        if len(outline.points) != len(glyph.coordinates):
            raise ValueError(f"Unexpected outline for {source.name}: {name}")
        error = freetype.FT_Outline_EmboldenXY(ctypes.byref(outline._FT_Outline), growth, growth)
        if error:
            raise ValueError(f"FreeType error {error} in {source.name}: {name}")
        glyph.coordinates = GlyphCoordinates(
            (new_x - old_x + x - growth // 2, new_y - old_y + y - growth // 2)
            for (x, y), (old_x, old_y), (new_x, new_y) in zip(glyph.coordinates, previous, outline.points)
        )
        glyph.program = Program()
        glyph.program.fromBytecode([])
    for name, old_x_min in original_x_min.items():
        glyph = glyf[name]
        glyph.recalcBounds(glyf)
        advance, bearing = metrics[name]
        metrics[name] = (advance, bearing + glyph.xMin - old_x_min)
    for record in font["name"].names:
        if record.nameID in {1, 3, 4, 6, 16, 18, 21}:
            value = record.toUnicode().replace("KaTeX_", "M2Print").replace("KaTeX", "M2Print")
            record.string = value.encode(record.getEncoding())
    font.flavor = "woff2"
    font.save(output)


def main():
    OUTPUT.mkdir(exist_ok=True)
    css = (KATEX / "katex.min.css").read_text()
    rules = re.findall(r"@font-face\{[^{}]+\}", css)
    with tempfile.TemporaryDirectory() as tmp:
        for rule in rules:
            filename = re.search(r"url\(fonts/([^()]+\.woff2)\)", rule)[1]
            strengthen_font(KATEX / "fonts" / filename, OUTPUT / filename.replace("KaTeX_", "M2Print"), Path(tmp) / "face.ttf")
    rules = [rule.replace("url(fonts/KaTeX_", "url(M2Print") for rule in rules]
    (OUTPUT / "fonts.css").write_text("/* Generated by build-print-math-fonts.py. */\n" + "\n".join(rules) + "\n")


if __name__ == "__main__":
    main()
